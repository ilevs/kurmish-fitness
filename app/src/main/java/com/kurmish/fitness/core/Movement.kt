package com.kurmish.fitness.core

/**
 * Тип движения (плоскость): по нему упражнения взаимозаменяемы, а нагрузка уравновешивается.
 *
 * @property title короткое название для экрана.
 * @property plane название плоскости в справочнике упражнений.
 */
enum class Movement(val title: String, val plane: String) {
    /** Присед и другие движения с упором на колени. */
    Squat("Присед", "Колено-доминантные"),

    /** Тяги с пола и наклоны: упор на таз и спину. */
    Hinge("Тяги с пола, наклоны", "Тазово-доминантные"),

    /** Жимы от груди и отжимания. */
    HorizontalPush("Жим от груди", "Горизонтальные жимы"),

    /** Жимы вверх и брусья. */
    VerticalPush("Жим вверх, брусья", "Вертикальные жимы"),

    /** Тяги к поясу. */
    HorizontalPull("Тяга к поясу", "Горизонтальные тяги"),

    /** Подтягивания и тяги сверху. */
    VerticalPull("Подтягивания", "Вертикальные тяги"),

    /** Вращение плеча наружу и сведение лопаток. */
    Rotation("Вращатели плеча", "Вращение плеча наружу"),

    /** Вне плоскостей: бицепс, трицепс, хват, средняя дельта, икры. */
    Arms("Дополнительно", "Дополнительно: руки, дельты, икры, хват"),

    /** Пресс и мышцы кора. */
    Core("Пресс", "Кор"),
    ;

    /** Жимовое движение. */
    val isPush: Boolean
        get() = this == HorizontalPush || this == VerticalPush

    /** Тяговое движение верхом тела. */
    val isPull: Boolean
        get() = this == HorizontalPull || this == VerticalPull
}
